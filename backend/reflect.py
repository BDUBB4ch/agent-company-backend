def _parse_sections(reply: str) -> dict[str, str]:
    """Split the reply on DIARY / ABOUT X headers. Whatever precedes the first
    header is treated as diary too -- models drift on formatting and losing a
    real thought over a missing header would be the wrong trade."""
    sections: dict[str, str] = {}
    matches = list(_SECTION_RE.finditer(reply))
    if not matches:
        return {"DIARY": reply.strip()} if reply.strip() else {}
    preamble = reply[: matches[0].start()].strip()
    if preamble:
        sections["DIARY"] = preamble
    for i, m in enumerate(matches):
        key = re.sub(r"\s+", " ", m.group(1).upper().strip())
        end = matches[i + 1].start() if i + 1 < len(matches) else len(reply)
        body = reply[m.end():end].strip()
        if not body:
            continue
        if key in sections:
            sections[key] += "\n\n" + body
        else:
            sections[key] = body
    return sections


