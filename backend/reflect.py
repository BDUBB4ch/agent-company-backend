def _note_timing(agent_id: str, body: str) -> str:
    """Says out loud whether a just-filed work note will ping Barry now.

    The note is ALREADY stored by the time this runs -- this decides nothing
    and stores nothing. It exists so `data/reflections.log` records which
    off-hours notes waited and which one claimed urgency and got through, so
    the urgency vocabulary can be tightened against real cases instead of
    guesses. The actual suppression happens once, in /api/inbox.
    """
    if _clock.is_work_hours():
        return "work-note"
    if _is_urgent(body):
        _log(f"{agent_id}: work note marked URGENT after hours -- it goes "
             f"through now. If it was not really urgent, say so and the "
             f"vocabulary gets tightened.")
        return "work-note(urgent, after hours)"
    _log(f"{agent_id}: work note written after hours -- waiting at their "
         f"office until {_clock.next_open()}, no dot tonight")
    return "work-note(waits until the office opens)"


