def _reflections_today(st: dict) -> int:
    d = st.get("_daily", {})
    return d.get("count", 0) if d.get("_day") == datetime.date.today().isoformat() else 0


def _is_placeholder(body: str) -> bool:
    t = re.sub(r"[\[\]()*_`.\-\s]", "", (body or "").lower())
    return t in ("", "empty", "none", "nothing", "na", "nothingtoreport", "nothingtonight", "nothingtoday",
                 "leaveempty", "nonetonight", "notonight", "skip")


def _due(st: dict, agent_id: str) -> bool:
    rec = st.get(agent_id) or {}
    if time.time() - rec.get("last_at", 0) < MIN_HOURS_BETWEEN * 3600:
        return False
    rows = memory.get_recent_history(agent_id, RECENT_TURNS)
    fresh = [r for r in rows if r["id"] > rec.get("last_turn", 0)]
    # their own life counts too (2026-10-16, _own_life): one real experience since the last journal is enough
    return len(fresh) >= MIN_FRESH_TURNS or bool(_own_life(agent_id, float(rec.get("last_at", 0) or 0)))


async def run_reflection_loop(get_agent_fn) -> None:
    """Background task, started in main.py's lifespan next to ideation.
    Same never-crash / never-compete citizenship as the ideation loop."""
    import ideation
    from agents import AGENTS
    while True:
        await asyncio.sleep(CHECK_INTERVAL_SECONDS)
        try:
            if not ideation._is_idle():
                continue
            st = _state()
            did_full = False
            if _reflections_today(st) < MAX_PER_DAY_TOTAL:
                # 2026-09-06: the one who has waited LONGEST goes first. The old
                # loop walked the roster in dict order and broke after one, so
                # whenever several were due the same seats (Victor, Amara)
                # reflected and the tail of the roster starved -- measured:
                # business 35 reflections, marketing 7, creative 7.
                due = [a for a in life_roster() if _due(st, a)]
                due.sort(key=lambda a: (st.get(a) or {}).get("last_at", 0))
                if due:
                    await reflect_once(get_agent_fn, due[0])
                    did_full = True   # one per wake -- the office stays responsive
            # between journal sittings, the default mode network: someone's
            # mind wanders. Random member -- idle thought is not scheduled.
            if not did_full and _stray_due(st):
                import random
                await stray_thought(get_agent_fn, random.choice(life_roster()))
        except Exception as e:
            _log(f"loop error (living on): {e}")
