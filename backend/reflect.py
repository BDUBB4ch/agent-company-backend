# Nothing is suggested about WHAT to think; only that they think about it.
REVISIT_MIN_AGE_DAYS = 3
REVISIT_ITEMS = 3
_REVISIT_LINE_RE = re.compile(r"^\s*\(?\s*(R\d+)\s*\)?\s*[:\-]?\s*(KEEP|ADD|ALTER|DROP)\b\s*[:\-]?\s*(.*)$", re.I)


def _revisit_candidates(office: str) -> list[dict]:
    """A few older conclusions worth a second look: the most important
    mind- entries that are at least a few days old (ranked by importance,
    oldest first among equals), plus one lesson from the ledger."""
    import lessons
    cut = (datetime.datetime.now(datetime.UTC) - datetime.timedelta(days=REVISIT_MIN_AGE_DAYS)).isoformat()
    out: list[dict] = []
    with memory.get_db() as conn:
        rows = conn.execute(
            "SELECT id, source_name, content, importance, created_at FROM facts "
            "WHERE category = ? AND status = 'active' AND created_at < ? AND ("
            "source_name LIKE 'mind-about-%' OR source_name = 'mind-on-life.md' "
            "OR source_name LIKE 'mind-diary-%') "
            "ORDER BY COALESCE(importance, 5) DESC, created_at ASC LIMIT 12",
            (f"private:{office}", cut)).fetchall()
    for r in rows[: REVISIT_ITEMS - 1]:
        out.append({"kind": "fact", "id": r["id"], "source_name": r["source_name"],
                    "when": (r["created_at"] or "")[:10], "text": (r["content"] or "").strip()})
    items = lessons.load(office)
    if items:
        idx = min(range(len(items)), key=lambda i: items[i].get("date", ""))   # the oldest lesson
        it = items[idx]
        out.append({"kind": "lesson", "index": idx, "when": it.get("date", ""),
                    "text": (it.get("lesson", "") + (" WHY: " + it["why"] if it.get("why") else "")
                             + (" HOW: " + it["how"] if it.get("how") else "")).strip()})
    return out


def _revisit_block(cands: list[dict]) -> str:
    if not cands:
        return ""
    lines = ["\n\nREVISIT: (for each item below, one line -- this is how you evolve)\n"
             "These are things YOU concluded earlier. Read each one as it stands now "
             "and decide: still true as written -> `R1 KEEP`; true but there is more "
             "to it now -> `R1 ADD: <the sentence to add>`; changed, out of date, or "
             "you would put it differently now -> `R1 ALTER: <the whole thing, rewritten "
             "as it stands today>`; no longer true at all -> `R1 DROP`. Whatever you "
             "write replaces the old version; nothing is kept twice. Your base self "
             "(Barry's words about who you are) is not on this list and cannot be "
             "touched here -- this is your own thinking, built on top of it.\n"]
    for i, c in enumerate(cands, 1):
        label = ("a lesson you keep on your ledger" if c["kind"] == "lesson"
                 else c["source_name"].replace("mind-", "").replace(".md", "").replace("-", " "))
        text = re.sub(r"^\[[^\]]*\]\s*", "", c["text"]).strip()
        if len(text) > 700:
            text = text[:700].rstrip() + " [...]"
        lines.append(f"\nR{i} ({label}, written {c['when'] or 'earlier'}):\n{text}\n")
    return "".join(lines)


def _apply_revisit(office: str, first_name: str, agent_id: str, body: str,
                   cands: list[dict]) -> list[str]:
    """Apply KEEP/ADD/ALTER/DROP lines to the candidates they refer to.
    Returns what changed, for the receipt. Never raises."""
    import lessons
    done: list[str] = []
    # group continuation lines under the last R# seen (ALTER text can span lines)
    ops: dict[str, tuple[str, list[str]]] = {}
    cur = None
    for ln in (body or "").splitlines():
        m = _REVISIT_LINE_RE.match(ln)
        if m:
            cur = m.group(1).upper()
            ops[cur] = (m.group(2).upper(), [m.group(3).strip()])
        elif cur and ln.strip():
            ops[cur][1].append(ln.rstrip())
    today = datetime.date.today().isoformat()
    for ref, (op, parts) in ops.items():
        try:
            n = int(ref[1:]) - 1
            if not (0 <= n < len(cands)):
                continue
            c = cands[n]
            text = "\n".join(p for p in parts if p is not None).strip()
            if c["kind"] == "lesson":
                items = lessons.load(office)
                if not (0 <= c["index"] < len(items)):
                    continue
                if op == "DROP":
                    lessons.forget(office, first_name, c["index"]); done.append(f"{ref} lesson dropped")
                elif op in ("ADD", "ALTER") and len(text) >= 8:
                    it = items[c["index"]]
                    it["lesson"] = (it.get("lesson", "") + " " + text).strip() if op == "ADD" else text
                    it["date"] = today; it["revised"] = int(it.get("revised", 0)) + 1
                    lessons._save(office, items); lessons.refresh_ledger(office, first_name)
                    done.append(f"{ref} lesson {op.lower()}ed")
                else:
                    done.append(f"{ref} kept")
                continue
            # a mind- fact
            with memory.get_db() as conn:
                row = conn.execute("SELECT id, source_name, content, importance FROM facts WHERE id = ? AND status = 'active'",
                                   (c["id"],)).fetchone()
            if not row:
                continue
            title_map = {"mind-on-life.md": f"{first_name} on life, their life, their world"}
            title = title_map.get(row["source_name"]) or (
                f"What {first_name} thinks of {row['source_name'][11:-3].replace('-', ' ').title()}"
                if row["source_name"].startswith("mind-about-") else f"{first_name}'s diary")
            if op == "DROP":
                with memory.get_db() as conn:
                    conn.execute("UPDATE facts SET status = 'superseded' WHERE id = ?", (row["id"],))
                done.append(f"{ref} dropped ({row['source_name']})")
            elif op == "ALTER" and len(text) >= 20:
                _store(office, row["source_name"], title,
                       f"[{first_name}, revised on {today}]\n\n{text}", row["importance"])
                done.append(f"{ref} altered ({row['source_name']})")
            elif op == "ADD" and len(text) >= 8:
                _store(office, row["source_name"], title,
                       (row["content"] or "").rstrip() + f"\n\n[{first_name}, added on {today}] {text}",
                       row["importance"])
                done.append(f"{ref} added to ({row['source_name']})")
            else:
                done.append(f"{ref} kept")
        except Exception as exc:  # noqa: BLE001 -- one bad line must not cost the rest
            _log(f"{agent_id}: REVISIT {ref} failed: {exc}")
    return done


