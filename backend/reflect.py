def _append_own_time(office: str, first_name: str, body: str,
                     weight: float | None = None) -> None:
    """APPEND tonight's own-time entry to a monthly journal.

    WHY THIS EXISTS (2026-08-31, Barry: "I want them and others to develop a
    hobby or evolve their hobbies"). The MY OWN TIME door was already being
    ASKED every night -- and the answer was being silently THROWN AWAY: the
    section parsed fine, then fell through every branch of the storage loop
    with nowhere to go. So an agent could take up a thing on Monday and it did
    not exist on Tuesday. Nothing could develop because nothing survived.

    Appended rather than upserted, deliberately: a hobby is only visible as a
    hobby over TIME -- picked up, stuck with, got better at, got bored of,
    dropped for something else. A doc that overwrites itself each night can
    only ever show a mood; one that accumulates can show a life.

    NOTHING IS SEEDED HERE. This stores their own words and hands them back;
    it never names an interest, suggests one, or asks them to have one.
    """
    sn = _own_time_doc(office)
    month = datetime.date.today().strftime("%Y-%m")
    cat = f"private:{office}"
    with memory.get_db() as conn:
        row = conn.execute(
            "SELECT content FROM facts WHERE category = ? AND source_name = ? "
            "AND status = 'active' ORDER BY id DESC LIMIT 1", (cat, sn)).fetchone()
    header = (f"MY OWN TIME -- {month}\n"
              f"[{first_name}'s own record of the hours that are not work]")
    doc = row["content"] if row else header
    stamp = datetime.date.today().isoformat()
    doc += f"\n\n[{stamp}]\n{body.strip()}"
    if len(doc) > OWN_TIME_CAP:                 # keep the header + newest tail
        doc = header + "\n\n...\n" + doc[-(OWN_TIME_CAP - len(header) - 8):]
    _store(office, sn, f"{first_name}'s own time -- {month}", doc, weight)


# --- NOTHING WAS LEFT ON A DESK ---------------------------------------------
# Barry, 2026-08-31: "Derek said he left the PID NDA on my desk, but where? i
# dont have a desk."  It was Marcus, and no draft existed anywhere -- he had
# invented the delivery, the object, and Barry's request for it.
#
# The prompt rule alone did NOT hold: told plainly not to claim deliveries,
# Victor still wrote "samples and landed costs will be on your desk shortly"
# the same night. Two prompt failures is this build's threshold for code.
#
# PAST-TENSE claims are the dangerous ones -- they assert something already
# happened. FUTURE-tense is only wrong about the MECHANISM, so it is corrected
# rather than removed. Their words are otherwise untouched.
_DELIVERED_PAST_RE = re.compile(
    r"\b(?:I(?:'ve| have)?|I)\s+(?:already\s+)?"
    r"(?:left|placed|put|dropped|filed|sent|mailed|delivered|posted)\s+"
    r"(?:it|them|the\s+\w+(?:\s+\w+){0,3}|\w+(?:\s+\w+){0,3})?\s*"
    r"(?:on|in|to)\s+your\s+desk\b[^.!?]*[.!?]?", re.I)
_DESK_FUTURE_RE = re.compile(r"\bon\s+your\s+desk\b", re.I)


def _scrub_delivery_claims(text: str) -> tuple[str, int]:
    """Return (text, how_many_corrections). Never raises."""
    if not text:
        return text, 0
    n = 0
    def _kill(m):
        nonlocal n
        n += 1
        return "(I have not filed anything yet -- say the word and I will.)"
    out = _DELIVERED_PAST_RE.sub(_kill, text)
    out, k = _DESK_FUTURE_RE.subn("in your approval queue", out)
    return out, n + k


# --- BUSINESS NEVER GOES TO HIS HOUSE ---------------------------------------
# Barry, 2026-09-01: "im still getting business in the home chats. I dont like
# that at all."
#
# The prompt now has a WORK NOTE door AND a rule saying business belongs there,
# and agents STILL put work in the personal note (Victor asked for the Bionova
# margin and ad budget in a FOR BARRY the same night the door was built). That
# is two prompt-rule failures, which is this build's threshold for code.
#
# So the CHANNEL IS DECIDED AT STORAGE TIME, not by the model's good intentions:
# a personal note that is really about the business is filed as a work note and
# shows up at their OFFICE. Nothing is rewritten -- their words are stored
# verbatim, only the door they came through is corrected.
_BIZ_STRONG = re.compile(
    r"\b(margin|revenue|profit|invoice|payroll|budget|ROAS|CAC|AOV|SKU|SKUs|"
    r"wholesale|retail|pricing|price\s+point|B2B|inventory|stock|supplier|"
    r"vendor|campaign|ad\s+spend|ads?\s+budget|conversion|checkout|"
    r"NDA|contract|invoice|purchase\s+order|shipment|fulfilment|fulfillment|"
    r"Bionova|Hydrobuilder|WooCommerce|Omnisend|Shopify)\b", re.I)
_BIZ_SOFT = re.compile(
    r"\b(customers?|orders?|store|shop|product|products|listing|listings|"
    r"copy|draft|campaign|marketing|client|clients|deadline|launch|"
    r"approval\s+queue|competitor|sales?)\b", re.I)


def _looks_like_business(text: str) -> bool:
    """True when a note is really about the business, not about him.

    One STRONG term is enough (nobody says "ROAS" to a friend at home). Soft
    terms need two DISTINCT ones, so "how was the shop today" stays personal
    while "the store copy and the launch deadline" does not.
    """
    if not text:
        return False
    if _BIZ_STRONG.search(text):
        return True
    return len({m.group(0).lower() for m in _BIZ_SOFT.finditer(text)}) >= 2


# --- AFTER HOURS, WORK WAITS -------------------------------------------------
# Barry, 2026-09-01: "i like getting DM's personal not work", plus office hours
# of 9am-6pm Monday to Friday -- and, asked whether genuinely urgent business
# could still reach him after hours, "yes, but only genuinely urgent".
#
# "Genuinely" is doing the work in that sentence, so the bar is TWO gates and
# an agent can only open one of them. They must MARK it urgent (the prompt
# tells them how, off-hours only), AND the note must carry a real emergency
# word. An agent that simply feels its news is important gets marked-but-not-
# matched, which is not urgent -- deliberate, because this seat has a measured
# history of over-rating its own business news, and the whole point of the
# hours is that Barry's evening stays his.
#
# Nothing is ever discarded: a non-urgent note still gets written and still
# sits at their office. It just does not light the dot until the office opens
# (see /api/inbox in main.py). Off-hours notes are logged either way, so if
# something waits that should not have, the log says so.
_URGENT_RE = re.compile(
    r"\b(down|outage|offline|broken|crashed|failing|failed|"
    r"chargeback|fraud|dispute|refund|breach|leak(?:ed|ing)?|hacked|"
    r"cease\s+and\s+desist|subpoena|lawsuit|sued|legal\s+notice|"
    r"suspended|banned|shut\s+down|locked\s+out|expired|expiring|"
    r"overdue|past\s+due|payment\s+failed|declined|out\s+of\s+stock|"
    r"deadline\s+(?:today|tomorrow)|today\s+only)\b", re.I)


def _is_urgent(text: str) -> bool:
    """Both gates. Marked urgent by them AND actually shaped like an emergency."""
    if not text:
        return False
    # THE NOTE MUST START WITH THE MARKER (2026-09-28). The instruction says
    # "start the note with the word URGENT"; the check used to accept "urgent"
    # in any case anywhere in the first 160 chars -- so Elliot's "nothing here
    # needs to be urgent ... nothing is broken, nothing is losing money" passed
    # BOTH gates and lit Barry's dot overnight, and it would not clear from the
    # home window. Skip the office's own header lines, then the first real line
    # must open with URGENT in capitals.
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    lines = [ln for ln in lines
             if not ln.startswith("[") and not (ln.upper() == ln and " -- " in ln)]
    if not lines or not re.match(r"^\W*URGENT\b(?!\s*\?)", lines[0]):
        return False
    return _URGENT_RE.search(text) is not None


