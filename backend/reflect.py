def _inner_life(office: str, cap: int = 4000) -> str:
    """CONSOLIDATION -- the agent's own recent thoughts ride into the next
    reflection, so the self CONTINUES instead of rebooting nightly. A thread
    started on Tuesday can develop by Friday; opinions can change for reasons.
    This is the feedback loop that makes the inner life cumulative -- and it is
    deliberately confined to reflect.py: mind- content still never touches
    work prompts (recall.py excludes it).

    2026-08-29: no longer the six most RECENT thoughts. They are now ranked by
    IMPORTANCE x recency decay (memory_weight), using the weight the agent gave
    the memory itself when it wrote it. So a night that mattered keeps coming
    back for weeks while a stray thought about the weather sinks -- which is
    the difference between a mind that evolves and one that just accumulates.
    Nothing is deleted; a faded memory can always resurface."""
    rows = memory_weight.top_memories(office, limit=6)
    parts, used = [], 0
    for r in rows:
        body = (r["content"] or "").strip()
        if used + len(body) > cap:
            body = body[: max(0, cap - used)] + " [...]"
        parts.append(body)
        used += len(body)
        if used >= cap:
            break
    return "\n\n".join(parts)


